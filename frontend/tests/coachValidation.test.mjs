import test from 'node:test';
import assert from 'node:assert/strict';
import {validateCoachPlan} from '../src/coachValidation.ts';
const phase=()=>({formation:'4-3-3',board:Array.from({length:11},()=>({x:60,y:40,name:'',task:''})),rivals:Array.from({length:11},()=>({x:60,y:40,name:'',task:''})),showRivals:true,movements:[{player:0,kind:'Run',x:80,y:40}],zones:[{kind:'Press',x:10,y:10,w:20,h:20}]});
const fixture=()=>({version:1,scenario:'Hücum',opponent:'Barcelona',objective:'Press',notes:'',phase:'In Possession',phases:{'In Possession':phase(),'Out of Possession':phase(),Transition:phase()},tasks:[{id:1,label:'Review',done:false}]});
test('valid plan round trip',()=>{const p=fixture();assert.deepEqual(validateCoachPlan(JSON.parse(JSON.stringify(p)),p.scenario),p)});
const invalid=(name,mutate)=>test(name,()=>{const p=fixture();mutate(p);assert.throws(()=>validateCoachPlan(p,'Hücum'))});
invalid('wrong version',p=>p.version=2);
invalid('wrong scenario',p=>p.scenario='Other');
invalid('missing phase',p=>delete p.phases.Transition);
invalid('invalid active phase',p=>p.phase='Other');
invalid('invalid formation',p=>p.phases.Transition.formation='5-5');
invalid('missing player',p=>p.phases.Transition.board.pop());
invalid('out of bounds player',p=>p.phases.Transition.board[0].x=121);
invalid('nonfinite coordinate',p=>p.phases.Transition.board[0].y=NaN);
invalid('invalid movement player',p=>p.phases.Transition.movements[0].player=11);
invalid('invalid movement kind',p=>p.phases.Transition.movements[0].kind='Other');
invalid('zone extends outside pitch',p=>p.phases.Transition.zones[0].w=120);
invalid('duplicate task ID',p=>p.tasks.push({...p.tasks[0]}));
invalid('unsafe task ID',p=>p.tasks[0].id=Number.MAX_SAFE_INTEGER+1);
invalid('oversized task list',p=>p.tasks=Array.from({length:1001},(_,i)=>({id:i+1,label:'Task',done:false})));
